/* edge_comments.c — 注释落位边界样本（保真度闭环用）
 * 覆盖：文件头块注释、函数内行注释、行尾行注释、行内块注释、struct 体成员前注释、
 * 枚举体首项前的独占行注释、声明符之间的行中块注释、文件尾无换行注释。
 * ⚠ 本样本**只放当前能保真的落位**——样本一旦变红就说明闭环回归，而不是把
 * 已知缺口当期望。
 *
 * 排版会与源不同（引擎按列表折叠/展开重排，源里的换行不保留），但**注释与
 * token 一条不丢、顺序不倒**，这正是本样本要守的性质。
 * ⚠ `int first …` 那行的注释刻意写短（列表 flat 不折行）：分隔符后行尾注释在
 * **跨折行**时落位会漂移（已知缺口，见 docs/gaps/gap-language-pack-scope.md §C 表 #8），
 * 写长了本样本就会以"已知缺口"的名义变红。
 */

